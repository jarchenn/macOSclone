#!/usr/bin/env python3
"""Generate C sources from build assets.

* Converts Spleen BDF bitmap fonts (ASCII 32..126) into C glyph tables.
* Emits a fixed-point sine table used by the wallpaper/icon generators so the
  kernel never needs floating point.
"""
import math
import sys
from pathlib import Path


def parse_bdf(path: Path):
    glyphs = {}
    width = height = None
    lines = path.read_text(encoding="ascii", errors="strict").splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("FONTBOUNDINGBOX"):
            _, w, h, _, _ = ln.split()
            width, height = int(w), int(h)
        if ln.startswith("ENCODING"):
            code = int(ln.split()[1])
            j = i
            while not lines[j].startswith("BITMAP"):
                j += 1
            rows = []
            for k in range(height):
                rows.append(int(lines[j + 1 + k], 16))
            glyphs[code] = rows
            i = j + height
        i += 1
    return width, height, glyphs


def emit_font(name: str, path: Path) -> str:
    w, h, glyphs = parse_bdf(path)
    nbytes = (w + 7) // 8
    out = [f"const struct font_data {name} = {{ {w}, {h}, {{"]
    for code in range(32, 127):
        rows = glyphs.get(code, [0] * h)
        vals = []
        for r in rows:
            # left-align into 16 bits (MSB = leftmost pixel)
            vals.append(r << (16 - nbytes * 8))
        out.append("  { " + ", ".join(f"0x{v:04x}" for v in vals) + " }, /* " + repr(chr(code)).replace("*/", "* /") + " */")
    out.append("} };")
    return "\n".join(out)


def emit_sine() -> str:
    vals = [int(round(math.sin(2 * math.pi * i / 256) * 4096)) for i in range(256)]
    rows = []
    for i in range(0, 256, 16):
        rows.append("  " + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    return "const int16_t sine_table_q12[256] = {\n" + "\n".join(rows) + "\n};"


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: gen_assets.py FONT8x16.bdf FONT12x24.bdf OUT.c", file=sys.stderr)
        return 2
    src = [
        "/* Generated by tools/gen_assets.py. Do not edit. */",
        "/* Glyphs: Spleen 2.2.0, Copyright (c) 2018-2026 Frederic Cambus, BSD-2-Clause. */",
        "#include \"graphics/font.h\"",
        "#include <stdint.h>",
        emit_font("font_spleen_8x16", Path(sys.argv[1])),
        emit_font("font_spleen_12x24", Path(sys.argv[2])),
        emit_sine(),
        "",
    ]
    Path(sys.argv[3]).write_text("\n".join(src), encoding="ascii")
    return 0


if __name__ == "__main__":
    sys.exit(main())
